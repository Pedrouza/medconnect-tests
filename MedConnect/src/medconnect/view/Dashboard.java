    private void carregarDadosDashboard() {
        try {
            int totalPacientes = pacienteDAO.contarTotal();
            int totalMedicos = medicoDAO.contarTotal();
            
            if (lblTotalPacientes != null) {
                lblTotalPacientes.setText(String.valueOf(totalPacientes));
            }
            if (lblTotalMedicos != null) {
                lblTotalMedicos.setText(String.valueOf(totalMedicos));
            }
            
            carregarTabelaConsultas();
            
        } catch (BancoException e) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Erro ao carregar dados: " + e.getMessage(), 
                "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
    
    private void carregarTabelaConsultas() {
        if (tblConsultas == null) return;
        
        DefaultTableModel modelo = (DefaultTableModel) tblConsultas.getModel();
        modelo.setRowCount(0);
        
        // Dados simulados para demonstração
        modelo.addRow(new Object[]{"Ana Silva", "08:00", "15/12", "Dra. Mei Lima"});
        modelo.addRow(new Object[]{"Cleber Purificação", "10:00", "16/12", "Dra. Ambrósio Fagundes"});
        modelo.addRow(new Object[]{"Paulo Mendes", "10:00", "17/12", "Dra. Mei Lima"});
    }

